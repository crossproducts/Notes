def by_category():
    out = {c[0]: [] for c in CATEGORIES}
    for aid in sorted(ARCHS):
        out[ARCHS[aid][0]].append(aid)
    return out


def filename(aid):
    return f"{aid}-{ARCHS[aid][1]}.md"


def check():
    assert len(ARCHS) == 101, f"expected 101 architectures, found {len(ARCHS)}"
    slugs = [v[1] for v in ARCHS.values()]
    assert len(set(slugs)) == len(slugs), "duplicate slug"
    for cid, items in by_category().items():
        assert items, f"category {cid} is empty"
    return True


if __name__ == "__main__":
    check()
    counts = {c[0]: len(v) for c, v in zip(CATEGORIES, by_category().values())}
    print(f"{len(ARCHS)} architectures across {len(CATEGORIES)} categories")
    for cid, cname, _ in CATEGORIES:
        print(f"  {cid} {cname:<42} {len(by_category()[cid]):>3}")
